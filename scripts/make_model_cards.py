def fmt(m: float, s: float, pct: bool = False) -> str:
    if pd.isna(m):
        return "—"
    return f"{m * 100:.1f} ± {s * 100:.1f}%" if pct else f"{m:.3f} ± {0 if pd.isna(s) else s:.3f}"


def thresholds(model: str, track: str) -> pd.DataFrame:
    rows = []
    for d in sorted(paths.MODELS.glob(f"{model}-{track}-*")):
        t = paths.MODELS / d.name / "threshold.json"
        meta = paths.MODELS / d.name / "meta.json"
        if t.exists() and meta.exists():
            m = json.loads(meta.read_text())
            td = m.get("training_data", {})
            rows.append({"source": td.get("dataset"), "seed": m.get("seed"), "variant": td.get("split_variant"),
                         "threshold": json.loads(t.read_text())["threshold"], "n_train": td.get("n_train"),
                         "split_hash": td.get("split_hash"), "bundle": d.name})
    return pd.DataFrame(rows)


def research_card(model: str) -> str:
    mcfg = config.load(paths.CONFIGS / "train/models" / f"{model}.yaml")["model"]
    lines = [f"# Model card: {NAMES[model]} (`{model}`)", "",
             "Research model of the cross-dataset study (C5/C6). Generated by `scripts/make_model_cards.py`.", "",
             "## Model", "", f"- Parameters: `{json.dumps(mcfg.get('params', {}))}`"]
    if mcfg.get("grid"):
        lines.append(f"- Grid (chosen by the lowest FPR at 95% DR on source validation): `{json.dumps(mcfg['grid'])}`")
    lines += ["- Preprocessing: median imputation and constant-column removal fitted on source train only "
              "(`preprocess.json` in each bundle).", "- Seeds: 0, 1, 2 (mean ± std below).", ""]
    for track in TRACKS:
        f = paths.TABLES / f"matrix_{track}.csv"
        if not f.exists():
            continue
        mt = pd.read_csv(f)
        mt = mt[mt.model == model]
        if mt.empty:
            continue
        th = thresholds(model, track)
        feats = schema.features(track)
        lines += [f"## Track `{track}`: {TRACKS[track]}", "",
                  f"- Features: {len(feats)} (`configs/tracks/{track}.yaml`); identifiers excluded by the schema "
                  "check; `dst_port` kept but flagged where present.", ""]
        if len(th):
            g = th[th.variant.isna()].groupby("source").agg(thr=("threshold", "mean"), thr_sd=("threshold", "std"),
                                                             n_train=("n_train", "first"),
                                                             split=("split_hash", "first"))
            lines += ["| Source (training data) | Train rows | Split hash | Frozen threshold (mean ± std) |",
                      "|---|---|---|---|"]
            for src, r in g.iterrows():
                sd = 0.0 if pd.isna(r.thr_sd) else r.thr_sd
                lines.append(f"| {src} | {int(r.n_train):,} | `{r.split}` | {r.thr:.6g} ± {sd:.2g} |")
            lines.append("")
        lines += ["| Source → target | Kind | FPR at thr | DR at thr | MCC | PR-AUC |", "|---|---|---|---|---|---|"]
        for _, r in mt.sort_values(["source", "kind", "target"], ascending=[True, False, True]).iterrows():
            lines.append(f"| {r.source} → {r.target} | {r.kind} | {fmt(r.fpr_at_thr_mean, r.fpr_at_thr_std, True)} "
                         f"| {fmt(r.dr_at_thr_mean, r.dr_at_thr_std, True)} | {fmt(r.mcc_at_thr_mean, r.mcc_at_thr_std)} "
                         f"| {fmt(r.pr_auc_mean, r.pr_auc_std)} |")
        if (mt[["fpr_at_thr_std", "dr_at_thr_std", "mcc_at_thr_std"]].fillna(0) == 0).all().all():
            lines += ["", "The three seeds give identical results on this track: training is deterministic for this "
                          "model (no row / column subsampling), so the seed changes nothing."]
        cross = mt[mt.kind == "cross"].sort_values("mcc_at_thr_mean")
        if len(cross):
            w = cross.head(3)
            lines += ["", "Worst cross-dataset cells: " + "; ".join(
                f"{r.source} → {r.target} (MCC {r.mcc_at_thr_mean:.2f}, DR {r.dr_at_thr_mean:.0%}, "
                f"FPR {r.fpr_at_thr_mean:.0%})" for _, r in w.iterrows()) + "."]
        lines.append("")
    lines += ["## Known failure cases and notes", ""] + [f"- {n}" for n in NOTES["all"] + NOTES.get(model, [])]
    lines += ["", "## Intended use", "",
              "Research measurement of cross-dataset generalisation on public lab datasets. Not a production detector: "
              "every result above shows it must be revalidated (and usually adapted with labels) on the network it "
              "is deployed in.", "", "## Provenance", "",
              "Bundles: `models/<model>-<track>-<source>-s<seed>-<cfg_hash>/` (meta.json holds the MLflow run ID, "
              "git commit and split hash). Every matrix cell lists its run IDs in `reports/tables/matrix_<track>.csv`."]
    return "\n".join(lines) + "\n"


