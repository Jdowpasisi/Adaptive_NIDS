def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    written = []
    for m in NAMES:
        (OUT / f"{m}.md").write_text(research_card(m))
        written.append(f"{m}.md")
    for name, text in live_cards().items():
        (OUT / name).write_text(text)
        written.append(name)
    index = ["# Model cards", ""] + [f"- [{w}]({w})" for w in written]
    (OUT / "README.md").write_text("\n".join(index) + "\n")
    print("wrote", ", ".join(written))


if __name__ == "__main__":
    main()
